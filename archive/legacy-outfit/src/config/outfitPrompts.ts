export function buildOutfitPrompt(input: {
  style?: OutfitStyle;
  userProfile?: string;
  occasion?: string;
  weather?: string;
  wardrobe?: unknown;
}) {
  return [
    BASE_OUTFIT_PROMPT,
    input.style ? `【指定风格】\n${STYLE_PROMPTS[input.style]}` : '',
    `【用户约束】\n${input.userProfile ?? '无额外约束'}`,
    `【场景与天气】\n场合：${input.occasion ?? '日常'}\n天气：${input.weather ?? '未知'}`,
    `【衣橱数据】\n${JSON.stringify(input.wardrobe ?? [])}`,
    '请只返回可执行的穿搭方案，并按固定输出要求解释原因。',
  ].filter(Boolean).join('\n\n');
}
